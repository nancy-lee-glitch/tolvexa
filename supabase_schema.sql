-- 3. USERS TABLE
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    role VARCHAR(20) DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN', 'VIP')),
    credits INTEGER DEFAULT 10 CHECK (credits >= 0),
    is_vip BOOLEAN DEFAULT FALSE,
    vip_expires_at TIMESTAMPTZ DEFAULT NULL,
    registration_ip VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index for instant lookup on username and email
CREATE INDEX IF NOT EXISTS idx_users_username ON public.users(username);
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_users_registration_ip ON public.users(registration_ip);

-- 4. 100% REAL-TIME ACTIVE TRADER PRESENCE TABLE
-- Tracks genuine connected WebSocket & browser clients via 30s sliding heartbeat
CREATE TABLE IF NOT EXISTS public.active_sessions (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    session_id VARCHAR(128) NOT NULL UNIQUE,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    ip_address VARCHAR(64) NOT NULL,
    active_asset VARCHAR(32) DEFAULT 'EUR/USD',
    last_heartbeat TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_active_sessions_heartbeat ON public.active_sessions(last_heartbeat);

-- 5. QUANTITATIVE SIGNALS TABLE (Forex, Synthetics, & MT5 Setups)
CREATE TABLE IF NOT EXISTS public.signals (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    asset VARCHAR(32) NOT NULL,
    timeframe VARCHAR(16) NOT NULL,
    direction VARCHAR(8) NOT NULL CHECK (direction IN ('CALL', 'PUT', 'BUY', 'SELL')),
    entry_price NUMERIC(16, 5) NOT NULL,
    target_price NUMERIC(16, 5),
    stop_loss NUMERIC(16, 5),
    take_profit_1 NUMERIC(16, 5),
    take_profit_2 NUMERIC(16, 5),
    confidence NUMERIC(5, 2) NOT NULL,
    confluence_factors JSONB DEFAULT '[]'::JSONB,
    setup_name VARCHAR(128),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_signals_created_at ON public.signals(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_signals_asset ON public.signals(asset);

-- 6. VERIFIED TRADE OUTCOMES & ACCURACY AUDIT TRAIL
CREATE TABLE IF NOT EXISTS public.trade_outcomes (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    signal_id UUID REFERENCES public.signals(id) ON DELETE SET NULL,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    asset VARCHAR(32) NOT NULL,
    timeframe VARCHAR(16) NOT NULL,
    direction VARCHAR(8) NOT NULL,
    entry_price NUMERIC(16, 5),
    exit_price NUMERIC(16, 5),
    pip_diff NUMERIC(8, 2),
    outcome VARCHAR(8) NOT NULL CHECK (outcome IN ('WIN', 'LOSS', 'DRAW')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_trade_outcomes_user ON public.trade_outcomes(user_id);
CREATE INDEX IF NOT EXISTS idx_trade_outcomes_outcome ON public.trade_outcomes(outcome);


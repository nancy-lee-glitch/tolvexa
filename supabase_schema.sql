-- 9. PRUNE STALE SESSIONS FUNCTION (Real Presence Cleanup)
-- Drops any connection inactive for > 45 seconds
CREATE OR REPLACE FUNCTION public.prune_stale_sessions()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    deleted_rows INTEGER;
BEGIN
    DELETE FROM public.active_sessions
    WHERE last_heartbeat < (NOW() - INTERVAL '45 seconds');
    GET DIAGNOSTICS deleted_rows = ROW_COUNT;
    RETURN deleted_rows;
END;
$$;

